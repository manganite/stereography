/**
 * The point group of a list of operations, and the operations described geometrically, for any
 * list (for instance the operations left after distorting a crystal; docs/conventions.md, "Point
 * group of a list of operations"). Shared by both entry points.
 */
import { det, multiply, trace } from '../linalg.js';
import { checkOrthogonal, checkTimeReversal } from '../operations.js';
import { EPSILON } from '../tolerances.js';
import { axialVector, rotationAxis } from './elements.js';
import { MAGNETIC_POINT_GROUP_KEYS, operations as groupOperations, settings, } from './pointGroups.js';
/** Throws unless mᵀm = 1 within the tolerance (a matrix with rounding errors passes with a larger one). */
function checkOrthogonalWithin(m, what, tolerance) {
    if (tolerance <= EPSILON) {
        checkOrthogonal(m, what);
        return;
    }
    for (let i = 0; i < 3; i++) {
        for (let j = 0; j < 3; j++) {
            const d = m[0][i] * m[0][j] + m[1][i] * m[1][j] + m[2][i] * m[2][j];
            if (!(Math.abs(d - (i === j ? 1 : 0)) < tolerance)) {
                throw new RangeError(`${what} is not an orthogonal (Cartesian) matrix: ${JSON.stringify(m)}`);
            }
        }
    }
}
/** No point group has more than 96 operations (m-3m1'). */
const MAX_ORDER = 96;
function toleranceOf(options) {
    const t = options?.tolerance ?? EPSILON;
    if (!(typeof t === 'number' && t > 0 && t < 0.1))
        throw new RangeError(`Invalid tolerance: ${String(t)}`);
    return t;
}
/**
 * How far the trace of a matrix with entries within `tolerance` may lie from an integer: three
 * diagonal entries, so three times the tolerance (at least that of `EPSILON`).
 */
const traceTolerance = (tolerance) => 3 * Math.max(tolerance, EPSILON);
const same = (a, b, tolerance) => a.timeReversal === b.timeReversal &&
    a.matrix.every((row, i) => row.every((v, j) => Math.abs(v - b.matrix[i][j]) < tolerance));
/** The kind of an operation (rounded trace, sign of the determinant, time reversal): equal operations have the same. */
const kindOf = (op) => `${Math.round(trace(op.matrix))}${det(op.matrix) > 0 ? '+' : '-'}${op.timeReversal ? "'" : ''}`;
/**
 * The group the operations generate, or undefined if it is larger than any point group. The
 * operations of the list that are not yet in the group are taken as generators, and the group is
 * grown by multiplying each element by each generator until nothing new appears; a new operation
 * is compared only with the operations of its kind.
 */
function close(ops, tolerance) {
    const identity = {
        matrix: [
            [1, 0, 0],
            [0, 1, 0],
            [0, 0, 1],
        ],
        timeReversal: false,
    };
    const group = [];
    const byKind = new Map();
    const has = (op) => (byKind.get(kindOf(op)) ?? []).some((g) => same(g, op, tolerance));
    const push = (op) => {
        group.push(op);
        const k = kindOf(op);
        const list = byKind.get(k);
        if (list)
            list.push(op);
        else
            byKind.set(k, [op]);
    };
    push(identity);
    const generators = [];
    for (const s of ops) {
        if (has(s))
            continue;
        generators.push(s);
        for (let i = 0; i < group.length; i++) {
            for (const t of generators) {
                const product = {
                    matrix: multiply(group[i].matrix, t.matrix),
                    timeReversal: group[i].timeReversal !== t.timeReversal,
                };
                if (has(product))
                    continue;
                if (group.length >= MAX_ORDER)
                    return undefined;
                push(product);
            }
        }
    }
    return group;
}
/**
 * How many operations of each kind a group has: determinant, trace and time reversal of each. For
 * the 122 point groups these counts are all different (a test checks it), and since the 122 are
 * all point groups up to orientation, the counts identify the point group of any finite group of
 * crystallographic operations.
 */
const signature = (ops, tolerance = EPSILON) => ops
    .map((op) => {
    const t = trace(op.matrix);
    const rounded = Math.round(t);
    if (Math.abs(t - rounded) > traceTolerance(tolerance))
        return 'x'; // not a crystallographic operation
    return `${Math.round(det(op.matrix))}:${rounded}${op.timeReversal ? "'" : ''}`;
})
    .sort()
    .join(' ');
let bySignature;
function keyOfSignature(s) {
    if (!bySignature) {
        bySignature = new Map();
        for (const key of MAGNETIC_POINT_GROUP_KEYS)
            bySignature.set(signature(groupOperations(key)), key);
    }
    return bySignature.get(s);
}
/**
 * The point group generated by a list of Cartesian operations, for instance those left after
 * distorting a crystal: its key, and the setting whose operations it equals in the frame of symcrys
 * (absent if the group is the point group in another orientation). The list is closed into a group
 * first, two matrices being equal when no entry differs by `tolerance` (default `EPSILON`) or more.
 * Time reversal counts: a list with time reversal gives a magnetic point group. Returns undefined
 * if the operations generate no point group (an operation of order 5, a group larger than 96).
 * Throws a RangeError for a matrix that is not orthogonal (within `tolerance`, at least
 * `EPSILON`). The classes `1` and `-1` have one setting and no orientation, so they always have
 * setting 1.
 */
export function pointGroupOf(operations, options) {
    const tolerance = toleranceOf(options);
    checkTimeReversal(operations);
    operations.forEach((op, i) => checkOrthogonalWithin(op.matrix, `Operation ${i}`, tolerance));
    const group = close(operations, tolerance);
    if (!group)
        return undefined;
    const key = keyOfSignature(signature(group, tolerance));
    if (!key)
        return undefined;
    // The operations passed in generate the group; if each is an operation of a setting of the same
    // order, the group is that setting. Products are not compared, since their errors add up.
    const setting = settings(key, 'itc').find((s) => {
        const ops = groupOperations(key, { convention: 'itc', setting: s.index });
        return ops.length === group.length && operations.every((g) => ops.some((op) => same(g, op, tolerance)));
    });
    return Object.freeze(setting ? { key, setting: setting.index } : { key });
}
/**
 * The axis signed so that its first non-zero component, in the order x, y, z, is positive; a
 * component smaller than the tolerance counts as zero.
 */
function signed(v, tolerance) {
    const first = v.find((x) => Math.abs(x) >= Math.max(tolerance, EPSILON)) ?? 0;
    return first < 0 ? { axis: [-v[0] + 0, -v[1] + 0, -v[2] + 0], flip: true } : { axis: v, flip: false };
}
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
function describe(op, i, tolerance) {
    checkOrthogonalWithin(op.matrix, `Operation ${i}`, tolerance);
    const notCrystallographic = `Operation ${i} is not a crystallographic point operation`;
    // The trace of the rotation part is an integer exactly for the angles 360°/n, n = 1, 2, 3, 4, 6.
    const t = det(op.matrix) > 0 ? trace(op.matrix) : -trace(op.matrix);
    if (Math.abs(t - Math.round(t)) > traceTolerance(tolerance))
        throw new RangeError(notCrystallographic);
    // The order from the trace of the rotation part, 1 + 2 cos(360°/n): 3, −1, 0, 1, 2 for n = 1, 2, 3, 4, 6.
    const n = { 3: 1, [-1]: 2, 0: 3, 1: 4, 2: 6 }[Math.round(t)];
    if (n === undefined)
        throw new RangeError(notCrystallographic);
    const r = (det(op.matrix) > 0 ? op.matrix : op.matrix.map((row) => row.map((v) => -v)));
    const proper = det(op.matrix) > 0;
    const timeReversal = op.timeReversal;
    if (n === 1)
        return Object.freeze({ kind: proper ? 'identity' : 'inversion', order: 1, timeReversal });
    const { axis } = signed(rotationAxis(r, n), tolerance);
    const frozenAxis = Object.freeze({ cartesian: Object.freeze(axis) });
    const kind = proper ? 'rotation' : n === 2 ? 'mirror' : 'rotoinversion';
    if (n === 2)
        return Object.freeze({ kind, order: 2, axis: frozenAxis, timeReversal });
    const sense = dot(axialVector(r), axis) > 0 ? '+' : '-';
    return Object.freeze({ kind, order: n, axis: frozenAxis, sense, timeReversal });
}
/**
 * Each operation of a list described geometrically, in the order of the list: kind, n, the
 * Cartesian axis (rotation or rotoinversion axis, mirror normal) with its first non-zero component,
 * in the order x, y, z, positive, and for n ≥ 3 the sense about that axis. The axes are not named
 * by lattice directions, since the list need not belong to a setting; for a point group given by its
 * key, `describeOperations` names them. Throws a RangeError for a matrix that is not orthogonal or
 * not a crystallographic operation (a rotation part by an angle other than 360°/n, n = 1, 2, 3, 4,
 * 6), both within `tolerance` (default `EPSILON`, as for `pointGroupOf`).
 */
export function describeOperationsOf(operations, options) {
    const tolerance = toleranceOf(options);
    checkTimeReversal(operations);
    return Object.freeze(operations.map((op, i) => describe(op, i, tolerance)));
}
