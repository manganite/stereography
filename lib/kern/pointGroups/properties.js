/**
 * Properties of a point group that follow from its operations, directly or through the form of a
 * tensor (piezoelectric). They do not depend on the setting or the convention. Piezomagnetic,
 * magnetoelectric and ferromagnetic follow with the magnetic point groups (#13).
 */
import { INVERSION, det, matricesEqual } from '../linalg.js';
import { EPSILON } from '../tolerances.js';
import { compose, operation, operationsEqual } from '../operations.js';
import { POINT_GROUP_KEYS } from './data.js';
import { operations } from './pointGroups.js';
import { tensorForm } from '../tensors/tensorForm.js';
/** Operations in setting 1, the frame all stored data share. */
const stored = (key) => operations(key, { setting: 1 });
/** Contains the inversion. */
export function isCentrosymmetric(key) {
    return stored(key).some((op) => !op.timeReversal && matricesEqual(op.matrix, INVERSION));
}
/**
 * Polar (pyroelectric class): some direction is left unchanged by every operation, i.e. the group
 * average of the matrices, which projects onto the invariant vectors, is not zero.
 */
export function isPolar(key) {
    const ops = stored(key);
    for (let i = 0; i < 3; i++) {
        for (let j = 0; j < 3; j++) {
            let sum = 0;
            for (const op of ops)
                sum += op.matrix[i][j];
            if (Math.abs(sum / ops.length) > EPSILON)
                return true;
        }
    }
    return false;
}
/** Chiral (enantiomorphic class): proper rotations only. */
export function isChiral(key) {
    return stored(key).every((op) => det(op.matrix) > 0);
}
function sameSet(a, b) {
    return a.length === b.length && a.every((x) => b.some((y) => operationsEqual(x, y)));
}
const laueCache = new Map();
/** The Laue class: the centrosymmetric crystal class generated by the group and the inversion. */
export function laueClass(key) {
    const cached = laueCache.get(key);
    if (cached)
        return cached;
    const ops = stored(key);
    const withInversion = [...ops];
    for (const op of ops) {
        const product = compose(operation(INVERSION), op);
        if (!withInversion.some((x) => operationsEqual(x, product)))
            withInversion.push(product);
    }
    const laue = POINT_GROUP_KEYS.find((k) => isCentrosymmetric(k) && sameSet(withInversion, stored(k)));
    if (!laue)
        throw new Error(`laueClass: no centrosymmetric class matches ${key}`);
    laueCache.set(key, laue);
    return laue;
}
/**
 * Piezoelectric: the polarization can depend linearly on stress, i.e. a polar time-even tensor of
 * rank 3, symmetric in its last two indices, is allowed (ITA Table 3.2.2.1).
 */
export function isPiezoelectric(key) {
    return (tensorForm(key, { rank: 3, parity: 'polar', timeParity: 'i', intrinsic: 'jk' }, { setting: 1 }).basis.length > 0);
}
